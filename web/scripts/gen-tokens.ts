// Generates tokens.css (and optionally tokens.json) from the Nordic Rose tokens file.
//
//   node scripts/gen-tokens.ts                       project layout: src/data/tokens.ts -> src/styles/tokens.css
//   node tokens/gen-tokens.ts --tokens tokens/tokens.ts --css exports/tokens.css --json exports/tokens.json
//
// Runs automatically before `npm run dev` and `npm run build` in a project (see package.json).
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const arg = (name: string, fallback?: string) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? process.argv[i + 1] : fallback;
};
const tokensPath = resolve(arg("tokens", "src/data/tokens.ts")!);
const cssOut = resolve(arg("css", "src/styles/tokens.css")!);
const jsonOut = arg("json");
const { dark, highContrast, light, themes } = (await import(pathToFileURL(tokensPath).href)) as typeof import("./tokens.ts");
type Theme = typeof light;

const kebab = (key: string) =>
  key
    .replace(/([a-z])([A-Z])/g, "$1-$2")
    .replace(/([a-zA-Z])(\d)/g, "$1-$2")
    .toLowerCase();

function block(selector: string, tokens: Partial<Theme>, extra: Record<string, string> = {}, indent = ""): string {
  const lines = [...Object.entries(tokens), ...Object.entries(extra)].map(
    ([k, v]) => `${indent}  --${kebab(k)}: ${v};`,
  );
  return `${indent}${selector} {\n${lines.join("\n")}\n${indent}}`;
}

const css = `/* Generated by gen-tokens.ts from the Nordic Rose tokens file. Do not edit by hand. */

${block(":root", light, { radius: "0.875rem" })}

${block('[data-theme="dark"]', dark)}

@media (prefers-color-scheme: dark) {
${block(':root:not([data-theme="light"])', dark, {}, "  ")}
}

/* High contrast: opt-in via data-contrast="high", or automatically for prefers-contrast: more */
${block('[data-contrast="high"]', highContrast.light)}

${block('[data-contrast="high"][data-theme="dark"]', highContrast.dark)}

@media (prefers-color-scheme: dark) {
${block('[data-contrast="high"]:not([data-theme="light"])', highContrast.dark, {}, "  ")}
}

@media (prefers-contrast: more) {
${block(':root:not([data-contrast="normal"])', highContrast.light, {}, "  ")}
${block(':root:not([data-contrast="normal"])[data-theme="dark"]', highContrast.dark, {}, "  ")}
  @media (prefers-color-scheme: dark) {
${block(':root:not([data-contrast="normal"]):not([data-theme="light"])', highContrast.dark, {}, "    ")}
  }
}
`;

const write = (file: string, text: string) => {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
  console.log(`tokens: wrote ${file}`);
};
write(cssOut, css);

// JSON for non-Astro consumers (matplotlib/plotly scripts, plain HTML, Figma tooling...).
if (jsonOut) write(resolve(jsonOut), JSON.stringify({ cssVars: Object.fromEntries(Object.entries(themes).map(([n, t]) => [n, Object.fromEntries(Object.entries(t as Theme).map(([k, v]) => [kebab(k), v]))])), themes }, null, 2) + "\n");
