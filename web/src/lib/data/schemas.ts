/**
 * The shape of every piece of content the site renders, checked at build time.
 *
 * Each schema is typed against the TypeScript type the components already use (`z.ZodType<Project>`), so
 * the two can't drift: change one without the other and `astro check` fails. Objects are strict, so a
 * misspelled or unknown field ("summmary") fails the build instead of silently disappearing. Whatever data source is
 * active (local files today, a database later) must return data that passes these, or the build stops
 * with a message naming the bad field.
 */
import { z } from "astro/zod";
import type { Shop, Independent } from "@/lib/timpla";

// ───────── Timpla (generated by scripts/build-timpla-data.ts) ─────────
const tier = z.enum(["acclaimed", "recognised", "indie"]);

export const shopSchema: z.ZodType<Shop> = z.strictObject({
  slug: z.string().regex(/^[a-z0-9-]+$/),
  name: z.string(),
  tier,
  type: z.string(),
  ownership: z.string(),
  beans: z.string(),
  since: z.string(),
  endorsements: z.number(),
  sources: z.array(z.strictObject({ outlet: z.string(), url: z.url() })),
  signals: z.array(z.string()),
  specialty: z.string(),
  status: z.string(),
  website: z.string(),
  instagram: z.string(),
  branches: z.array(z.strictObject({
    name: z.string(),
    neighbourhood: z.string(),
    city: z.string(),
    address: z.string(),
    lat: z.number().nullable(),
    lon: z.number().nullable(),
    coordSource: z.string(),
  })).min(1),
});

export const independentSchema: z.ZodType<Independent> = z.strictObject({
  id: z.string().regex(/^[nwr]\d+$/, "an OpenStreetMap id like n123 / w456"),
  name: z.string(),
  cls: z.enum(["independent", "multibranch"]),
  city: z.string(),
  lon: z.number(),
  lat: z.number(),
  n: z.number(),
  ev: z.enum(["osm_check", "overture_2026_09"]),
  evd: z.string(),
  ig: z.string(),
  web: z.string(),
});

export const pointSchema = z.strictObject({
  slug: z.string(), name: z.string(), branch: z.string(), tier, city: z.string(), nb: z.string(),
  type: z.string(), own: z.enum(["local", "foreign"]), beans: z.string(), since: z.string(),
  lon: z.number(), lat: z.number(), xy: z.tuple([z.number(), z.number()]),
});
export type Point = z.infer<typeof pointSchema>;

export const timplaMetaSchema = z.strictObject({
  builtAt: z.string(),
  shops: z.number(),
  branches: z.number(),
  mapped: z.number(),
  tiers: z.record(tier, z.number()),
  roasterLinks: z.number(),
  beanListings: z.number(),
  listingTotal: z.number(),
  arabicaTotal: z.number(),
  allTotal: z.number(),
  directory: z.strictObject({
    shops: z.number(),
    branches: z.number(),
    classes: z.strictObject({ specialty: z.number(), independent: z.number(), multibranch: z.number() }),
    evidence: z.record(z.string(), z.number()),
    unverified: z.number(),
  }),
});
export type TimplaMeta = z.infer<typeof timplaMetaSchema>;

export const timelineSchema = z.strictObject({
  years: z.array(z.strictObject({ year: z.number(), opened: z.number(), openedIncluded: z.number(), closed: z.number() })),
  events: z.number(),
});
export const provenanceSchema = z.array(z.strictObject({
  province: z.string(), listings: z.number(), menuShare: z.number(),
  arabicaTonnes: z.number(), harvestShare: z.number(), allCoffeeShare: z.number(),
}));
export const ncrSchema = z.strictObject({
  path: z.string(),
  box: z.strictObject({ lon0: z.number(), lon1: z.number(), lat0: z.number(), lat1: z.number(), w: z.number(), h: z.number() }),
});
/** [lon, lat, name] */
export const osmLayerSchema = z.array(z.tuple([z.number(), z.number(), z.string()]));

// ───────── Tanim ─────────
const yearMap = z.record(z.string().regex(/^\d{4}$/), z.number().nullable());
const varietySeries = z.strictObject({ all: yearMap, robusta: yearMap, arabica: yearMap, excelsa: yearMap, liberica: yearMap });
export const tanimProvinceSchema = z.strictObject({
  psgc: z.number(), name: z.string(), region: z.string(), d: z.string(), cx: z.number(), cy: z.number(),
  production: varietySeries, area: varietySeries, trees: varietySeries, farmgate: varietySeries,
  cpi: z.record(z.string(), z.number()), fies: z.record(z.string(), z.number()),
  note: z.string().optional(),
});
export type TanimProvince = z.infer<typeof tanimProvinceSchema>;
export const tanimNationalSchema = z.strictObject({
  years: z.array(z.string()),
  production: varietySeries, area: varietySeries, trees: varietySeries, farmgate: varietySeries,
  sua: z.record(z.string(), yearMap), ssr: yearMap, idr: yearMap,
  valueOfProduction: z.strictObject({ current: yearMap, constant2018: yearMap }),
  cpi: z.record(z.string(), z.number()), fies: z.record(z.string(), z.number()),
  regions: z.array(z.strictObject({ name: z.string(), production: varietySeries, area: varietySeries, trees: varietySeries })),
});
export type TanimNational = z.infer<typeof tanimNationalSchema>;
const sankeyNode = z.strictObject({ name: z.string(), y0: z.number(), y1: z.number(), value: z.number(), x: z.number(), w: z.number() });
export const tanimImportsSchema = z.record(z.string(), z.strictObject({
  flows: z.array(z.strictObject({ origin: z.string(), name: z.string(), form: z.string(), kg: z.number(), usd: z.number() })),
  byForm: z.record(z.string(), z.strictObject({ kg: z.number(), usd: z.number() })),
  sankey: z.strictObject({
    width: z.number(), height: z.number(), unit: z.enum(["kg", "usd"]), total: z.number(),
    origins: z.array(sankeyNode), forms: z.array(sankeyNode),
    links: z.array(z.strictObject({ origin: z.string(), form: z.string(), value: z.number(), share: z.number(), d: z.string(), width: z.number() })),
  }),
}));
export type TanimImports = z.infer<typeof tanimImportsSchema>;
export const tanimReportedSchema = z.array(z.strictObject({ province: z.string(), text: z.string(), source: z.string(), date: z.string(), url: z.string() }));
export type TanimReported = z.infer<typeof tanimReportedSchema>;
export const tanimMetaSchema = z.strictObject({
  builtAt: z.string(), retrievedAt: z.string(),
  tables: z.record(z.string(), z.strictObject({ folder: z.string(), title: z.string(), updated: z.string().nullable() })),
  checks: z.array(z.strictObject({ check: z.string(), national: z.number().nullable(), regions: z.number(), ok: z.boolean() })),
  boundaries: z.strictObject({ source: z.string(), licence: z.string(), psgc: z.string(), features: z.number() }),
  years: z.array(z.string()), latestYear: z.string(), provinces: z.number(), reporting: z.number(), importYears: z.array(z.string()),
  box: z.strictObject({ w: z.number(), h: z.number() }),
});
export type TanimMeta = z.infer<typeof tanimMetaSchema>;
